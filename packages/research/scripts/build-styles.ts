/**
 * Embeds the vendored CSL styles and locale (`vendor/csl/`) as string constants in
 * `src/bibliography/styles.generated.ts`, so they load in Node, Vite and Next.js
 * without raw-file loaders.
 *
 *   pnpm --filter @longhand/research build-styles
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendor = join(root, 'vendor', 'csl');
const out = join(root, 'src', 'bibliography', 'styles.generated.ts');

const files = {
  apa: 'apa.csl',
  'modern-language-association': 'modern-language-association.csl',
  'chicago-author-date': 'chicago-author-date.csl',
} as const;

let ts = `// GENERATED by scripts/build-styles.ts from vendor/csl/. Do not edit.
// CSL styles and locale: © their authors, Creative Commons Attribution-ShareAlike 3.0
// (see vendor/csl/NOTICE.md and vendor/csl/CC-BY-SA-3.0.txt).

`;
ts += `/** Bundled CSL style XML by style id. */\nexport const STYLE_XML = {\n`;
for (const [id, file] of Object.entries(files)) {
  ts += `  ${JSON.stringify(id)}: ${JSON.stringify(readFileSync(join(vendor, file), 'utf8'))},\n`;
}
ts += `} as const;\n\n`;
ts += `/** Bundled CSL locale XML (en-US). */\nexport const LOCALE_EN_US = ${JSON.stringify(
  readFileSync(join(vendor, 'locales-en-US.xml'), 'utf8'),
)};\n`;
writeFileSync(out, ts);
console.log(`wrote ${out} (${ts.length} chars)`);
