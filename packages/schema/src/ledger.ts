/**
 * The ledger envelope: commits, the hash chain and witnesses.
 *
 * - One ledger per project: an append-only sequence of commits, `seq` 1, 2, 3…
 * - `hash = sha256Hex(canonicalize(commit without hash))`; `prevHash` of seq 1 is
 *   {@link GENESIS_PREV_HASH}; every later `prevHash` is the previous commit's `hash`.
 * - Clients submit a {@link CommitDraft}; the ledger service (the only writer)
 *   assigns `seq`, `prevHash`, `serverTime`, fills `accountId` from auth and
 *   computes `hash`, then witnesses the commit.
 * - A witness is an ECDSA P-256 / SHA-256 signature over
 *   `canonicalize({projectId, seq, hash, serverTime})`, encoded as base64 of the
 *   64-byte IEEE P1363 `r‖s` form (what WebCrypto produces and verifies; KMS DER
 *   signatures are converted). `keyId` is the hex SHA-256 of the SPKI DER public key.
 */
import { z } from 'zod';
import { canonicalHash, canonicalize, sha256Hex, utf8 } from './canonical';
import {
  ActorKindSchema,
  EVENTS,
  EVENT_TYPES,
  canActorEmit,
  type EventPayloads,
  type EventType,
} from './events';
import { IdSchema, IsoTimeSchema, SeqSchema, Sha256HexSchema } from './ids';

/** Current ledger schema version, stamped on every commit. Bumped by the coordinator on contract changes. */
export const SCHEMA_VERSION = 1;

/** `prevHash` of the first commit: 64 zeros. */
export const GENESIS_PREV_HASH = '0'.repeat(64);

/** Who authored a commit. Human ids are account user ids; agent ids are the model alias; system ids name the service. */
export const ActorSchema = z.object({ kind: ActorKindSchema, id: z.string().min(1).max(200) });
/** Who authored a commit. */
export type Actor = z.infer<typeof ActorSchema>;

/** Envelope fields shared by every commit. */
export interface CommitEnvelope {
  /** Idempotency key generated by the emitter (UUID). The ledger service dedupes resends by it. */
  commitId: string;
  projectId: string;
  accountId: string;
  /** 1-based position in the project ledger. */
  seq: number;
  /** `hash` of commit `seq - 1`, or {@link GENESIS_PREV_HASH} for seq 1. */
  prevHash: string;
  /** SHA-256 of the canonical JSON of this commit without `hash`. */
  hash: string;
  /** Client clock when the action happened (for `TextEdited`: the batch's first input event). Untrusted. */
  clientTime: string;
  /** Ledger service clock at ingest. Covered by the hash and the witness. */
  serverTime: string;
  actor: Actor;
  /** Emitting device (random per browser install); `server` for agent and system commits. */
  deviceId: string;
  /** Editor session (random per editor load) for human commits; the feedback session id for agent commits; `system` for system commits. */
  sessionId: string;
  schemaVersion: number;
}

/** A commit of event type `K`. */
export type CommitOf<K extends EventType> = CommitEnvelope & { type: K; payload: EventPayloads[K] };

/** Any commit (discriminated on `type`). */
export type Commit = { [K in EventType]: CommitOf<K> }[EventType];

/** What a client submits; the ledger service fills in the rest. */
export type CommitDraftOf<K extends EventType> = Omit<
  CommitOf<K>,
  'seq' | 'prevHash' | 'hash' | 'serverTime' | 'accountId'
>;

/** Any commit draft. */
export type CommitDraft = { [K in EventType]: CommitDraftOf<K> }[EventType];

const envelopeShape = {
  commitId: IdSchema,
  projectId: IdSchema,
  accountId: IdSchema,
  seq: SeqSchema,
  prevHash: Sha256HexSchema,
  hash: Sha256HexSchema,
  clientTime: IsoTimeSchema,
  serverTime: IsoTimeSchema,
  actor: ActorSchema,
  deviceId: z.string().min(1).max(100),
  sessionId: z.string().min(1).max(100),
  schemaVersion: z.literal(SCHEMA_VERSION),
};

const draftOmit = {
  seq: true,
  prevHash: true,
  hash: true,
  serverTime: true,
  accountId: true,
} as const;

type EnvelopeLike = { type: string; actor: { kind: z.infer<typeof ActorKindSchema> } };

function withActorCheck(variants: z.ZodObject[]): z.ZodType<EnvelopeLike> {
  const union = z.discriminatedUnion(
    'type',
    variants as unknown as [z.ZodObject, ...z.ZodObject[]],
  ) as unknown as z.ZodType<EnvelopeLike>;
  return union.refine((c) => canActorEmit(c.type, c.actor.kind), {
    message: 'this actor kind may not emit this event type',
    path: ['actor', 'kind'],
  });
}

const commitVariants = EVENT_TYPES.map((type) =>
  z.strictObject({ ...envelopeShape, type: z.literal(type), payload: EVENTS[type].payload }),
);
const draftVariants = EVENT_TYPES.map((type) =>
  z
    .strictObject({ ...envelopeShape, type: z.literal(type), payload: EVENTS[type].payload })
    .omit(draftOmit),
);

/**
 * Zod schema for a full commit. Validates the envelope, the payload for its
 * `type`, and that `actor.kind` may emit `type` (`canActorEmit`). Does not check
 * the hash or the chain (see {@link verifyCommitHash}).
 */
export const CommitSchema = withActorCheck(commitVariants) as unknown as z.ZodType<Commit>;

/** Zod schema for a commit draft (no seq, prevHash, hash, serverTime or accountId). */
export const CommitDraftSchema = withActorCheck(draftVariants) as unknown as z.ZodType<CommitDraft>;

/** Computes a commit's hash: SHA-256 of the canonical JSON of every field except `hash`. */
export function computeCommitHash(commit: Omit<Commit, 'hash'> | Commit): string {
  const { hash: _hash, ...rest } = commit as Commit;
  return canonicalHash(rest);
}

/** True if `commit.hash` matches its content. */
export function verifyCommitHash(commit: Commit): boolean {
  return computeCommitHash(commit) === commit.hash;
}

// ---------------------------------------------------------------------------
// Witnesses
// ---------------------------------------------------------------------------

/** The fields a witness signs. */
export interface WitnessSubject {
  projectId: string;
  seq: number;
  hash: string;
  serverTime: string;
}

/** Zod schema for a {@link Witness}. */
export const WitnessSchema = z.object({
  projectId: IdSchema,
  seq: SeqSchema,
  hash: Sha256HexSchema,
  serverTime: IsoTimeSchema,
  /** base64 (standard alphabet, padded) of the 64-byte P1363 `r‖s` ECDSA P-256 signature. */
  signature: z.string().regex(/^[A-Za-z0-9+/]{86}==$/, 'base64 of a 64-byte P1363 signature'),
  /** Hex SHA-256 of the signer's SPKI DER public key. */
  keyId: Sha256HexSchema,
});
/** The ledger service's signature over one commit. */
export type Witness = z.infer<typeof WitnessSchema>;

/** The exact bytes a witness signs: UTF-8 of `canonicalize({projectId, seq, hash, serverTime})`. */
export function witnessMessage(subject: WitnessSubject): Uint8Array {
  return utf8(
    canonicalize({
      projectId: subject.projectId,
      seq: subject.seq,
      hash: subject.hash,
      serverTime: subject.serverTime,
    }),
  );
}

/**
 * Something that signs witness messages (a PEM file locally, AWS KMS in prod).
 * Implementations return raw 64-byte P1363 signatures.
 */
export interface WitnessSigner {
  readonly keyId: string;
  readonly publicKeyPem: string;
  sign(message: Uint8Array): Promise<Uint8Array>;
}

/** Standard base64 (padded) encoding of bytes. Isomorphic. */
export function base64Encode(bytes: Uint8Array): string {
  let bin = '';
  for (let i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i] as number);
  return btoa(bin);
}

/** Decodes standard base64. Throws on invalid input. Isomorphic. */
export function base64Decode(text: string): Uint8Array {
  const bin = atob(text);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/** Extracts the DER bytes from a PEM block (`-----BEGIN PUBLIC KEY-----` …). */
export function pemToDer(pem: string): Uint8Array {
  const body = pem.replace(/-----(BEGIN|END) [A-Z ]+-----/g, '').replace(/\s+/g, '');
  return base64Decode(body);
}

/** Wraps DER bytes in a PEM block with the given label (default `PUBLIC KEY`). */
export function derToPem(der: Uint8Array, label = 'PUBLIC KEY'): string {
  const b64 = base64Encode(der);
  const lines = b64.match(/.{1,64}/g) ?? [];
  return `-----BEGIN ${label}-----\n${lines.join('\n')}\n-----END ${label}-----\n`;
}

/** `keyId` of a public key: hex SHA-256 of its SPKI DER bytes. */
export function keyIdFromSpkiDer(spkiDer: Uint8Array): string {
  return sha256Hex(spkiDer);
}

/** `keyId` of a PEM-encoded SPKI public key. */
export function keyIdFromPublicKeyPem(publicKeyPem: string): string {
  return keyIdFromSpkiDer(pemToDer(publicKeyPem));
}

/** Imports a PEM SPKI P-256 public key for WebCrypto verification. */
export async function importWitnessPublicKey(publicKeyPem: string): Promise<CryptoKey> {
  return globalThis.crypto.subtle.importKey(
    'spki',
    pemToDer(publicKeyPem) as Uint8Array<ArrayBuffer>,
    { name: 'ECDSA', namedCurve: 'P-256' },
    false,
    ['verify'],
  );
}

/**
 * Verifies a witness signature with WebCrypto (Node ≥ 20 and browsers). Checks the
 * signature only — callers also compare the witness fields with the commit and
 * `keyId` with the key.
 */
export async function verifyWitnessSignature(
  witness: Witness,
  publicKey: CryptoKey | string,
): Promise<boolean> {
  const key = typeof publicKey === 'string' ? await importWitnessPublicKey(publicKey) : publicKey;
  let sig: Uint8Array;
  try {
    sig = base64Decode(witness.signature);
  } catch {
    return false;
  }
  if (sig.length !== 64) return false;
  return globalThis.crypto.subtle.verify(
    { name: 'ECDSA', hash: 'SHA-256' },
    key,
    sig as Uint8Array<ArrayBuffer>,
    witnessMessage(witness) as Uint8Array<ArrayBuffer>,
  );
}
